"""Generate the password-gate configuration for the site.

The site is hosted on GitHub Pages, which is a purely static host: there is no
server to authenticate against.  The gate therefore has to run in the browser.

To avoid storing the password itself, this script derives a PBKDF2-HMAC-SHA256
hash (150 000 iterations, random 16-byte salt) and writes it into
``site/assets/js/auth-config.js`` together with the salt and iteration count.
The browser repeats exactly the same derivation and compares the results.

Usage:
    python make_auth_config.py --password "secret" [--force]

If ``--password`` is omitted the value is read from the ``SITE_PASSWORD``
environment variable.  The plaintext is never written to disk.
"""

import argparse
import base64
import hashlib
import os
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "site" / "assets" / "js" / "auth-config.js"

ITERATIONS = 150_000
KEY_LENGTH = 32


def derive(password: str, salt: bytes, iterations: int) -> bytes:
    return hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt,
                                iterations, KEY_LENGTH)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--password", help="site password")
    parser.add_argument("--force", action="store_true",
                        help="overwrite an existing configuration")
    args = parser.parse_args()

    if OUT.exists() and not args.force:
        print(f"{OUT} already exists - use --force to regenerate", file=sys.stderr)
        return 1

    password = args.password or os.environ.get("SITE_PASSWORD")
    if not password:
        print("provide --password or set SITE_PASSWORD", file=sys.stderr)
        return 1

    salt = secrets.token_bytes(16)
    digest = derive(password, salt, ITERATIONS)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// AUTO-GENERATED by tools/make_auth_config.py - do not edit by hand.\n"
        "// PBKDF2-HMAC-SHA256 parameters for the site password gate.\n"
        "export const AUTH_CONFIG = {\n"
        f"  salt: '{base64.b64encode(salt).decode()}',\n"
        f"  iterations: {ITERATIONS},\n"
        f"  hash: '{base64.b64encode(digest).decode()}',\n"
        "};\n",
        encoding="utf-8",
    )

    print(f"wrote {OUT}")
    print(f"  salt       {base64.b64encode(salt).decode()}")
    print(f"  iterations {ITERATIONS}")
    print(f"  hash       {base64.b64encode(digest).decode()}")
    print("\nThe plaintext password was not written to disk.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
